/**
 * Wheel events captured from real hardware, not synthesized.
 *
 * Source: Tauri (WKWebView) on macOS, MacBook trackpad, recorded with the
 * `wcap` console helper. Rows are [timeStamp, deltaX, deltaY, wheelDeltaY];
 * deltaMode was 0 throughout.
 *
 * What these captures establish, and what the classifier must keep honouring:
 *
 * - Pinch DOES arrive as `wheel` + ctrlKey inside WKWebView, alongside WebKit's
 *   proprietary GestureEvents. It is also the only capture with fractional
 *   deltas.
 * - A two-finger scroll leaks into the off-axis constantly (66 of 115 events
 *   here), so macOS axis locking does not zero deltaX for the DOM. This is the
 *   signal the classifier leans on.
 * - Trackpad scroll deltas are whole numbers, so "fractional means trackpad"
 *   never fires for scrolling here — only for pinch.
 * - wheelDeltaY is deltaY * -3 in both captures and never a multiple of 120,
 *   so the wheel-quantisation rule cannot misfire on this trackpad.
 */

export type CaptureRow = [t: number, dx: number, dy: number, wdy: number];

